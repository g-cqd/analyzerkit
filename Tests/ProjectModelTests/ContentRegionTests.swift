import Foundation
import SwiftParser
import Testing

@testable import ProjectModel

/// What a tool may cache about a file's region, and what it must decide per run (roadmap 0020). A file's content says
/// whether it imports a test framework or carries a generator's header; its project says which targets compile it, and
/// that changes without the file changing. So the content part is cached and the project part is joined to it per run.
@Suite struct ContentRegionTests {
    @Test func `the content region is the test import and the generator's header, and nothing else`() {
        #expect(
            ProjectClassification.contentRegion(path: "/p/A.swift", tree: Parser.parse(source: "import XCTest\n"))
                == .test)
        #expect(
            ProjectClassification.contentRegion(
                path: "/p/A.swift", tree: Parser.parse(source: "// Generated by protoc. DO NOT EDIT.\nlet a = 1\n"))
                == .generated)
        #expect(
            ProjectClassification.contentRegion(path: "/p/Tests/A.swift", tree: Parser.parse(source: "let a = 1\n"))
                .isEmpty)
    }

    @Test func `classify with a content region equals classify with the tree`() throws {
        try ProjectFixture.with { f in
            try f.file(
                "Package.swift",
                """
                // swift-tools-version: 6.0
                import PackageDescription
                let package = Package(name: "P", targets: [
                    .target(name: "Lib", path: "Lib"), .testTarget(name: "Checks", dependencies: ["Lib"], path: "Checks"),
                ])
                """)
            let sources = ["import XCTest\nlet a = 1\n", "let b = 1\n", "// Code generated by x. DO NOT EDIT.\n"]
            var files: [String] = []
            for (index, source) in sources.enumerated() {
                files.append(try f.file("Lib/F\(index).swift", source))
                files.append(try f.file("Checks/C\(index).swift", source))
            }
            let model = try f.classification(of: files)
            for (index, file) in files.enumerated() {
                let tree = Parser.parse(source: sources[index / 2])
                let content = ProjectClassification.contentRegion(path: file, tree: tree)
                #expect(model.classify(file, content: content) == model.classify(file, tree: tree), "\(file)")
            }
        }
    }
}
