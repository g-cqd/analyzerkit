import ProjectModel
import Testing

/// Characterization of the path conventions, pinned before they move from `String` comparison to bytes.
@Suite struct PathConventionTests {
    @Test(arguments: [
        ("/r/Tests/A.swift", true), ("/r/AppTests/A.swift", true), ("/r/AppUITests/Screens/A.swift", true),
        ("Tests/A.swift", true), ("/r/Sources/ThingTests.swift", true), ("/r/Sources/ThingTest.swift", true),
        ("/r/Sources/Tests.swift", true), ("/r/Sources/Test.swift", true), ("/r/Tests", true),
        ("/r/Sources/A.swift", false), ("/r/tests/A.swift", false), ("/r/Testsuite/A.swift", false),
        ("/r/App.Tests/A.swift", false), ("/r/Sources/Contest.swift", false), ("/r/Sources/Latest.swift", false),
        ("/r/Sources/ThingTests.swiftx", false), ("/r/Tésts/A.swift", false), ("/r/Sources/ThingTests.Swift", false),
        ("/r/Tests\u{301}/A.swift", false), ("", false), ("/", false), ("//Tests//", true),
    ])
    func `a path is test by its directories and name`(path: String, expected: Bool) {
        #expect(TestConventions.isTestPath(path) == expected, "\(path)")
    }

    @Test(arguments: [
        ("/r/Generated/A.swift", true), ("Generated/A.swift", true), ("/r/Sources/Model.generated.swift", true),
        ("/r/Generated", true), ("/r/a/Generated/b/c/A.swift", true),
        ("/r/generated/A.swift", false), ("/r/GeneratedCode/A.swift", false),
        ("/r/Sources/GeneratedReport.swift", false),
        ("/r/Sources/Model.Generated.swift", false), ("/r/Sources/Model.generated.swiftx", false),
        ("/r/Generated\u{301}/A.swift", false), ("/r/Sources/.generated.swift", true), ("", false),
    ])
    func `a path is generated by a Generated directory or a .generated.swift name`(path: String, expected: Bool) {
        #expect(GeneratedCode.isGenerated(path: path, header: "") == expected, "\(path)")
    }

    @Test(arguments: [
        ("// GENERATED BY protoc", true), ("/* Auto-Generated */", true), ("// AutoGenerated file", true),
        ("// @generated", true), ("// Do Not Edit", true), ("// generated using Sourcery", true),
        ("// Generated", false), ("// do not  edit", false), ("// regenerated by hand", true),
        ("// Gènerated by", false), ("", false),
    ])
    func `a header is generated by a marker, in any letter case`(header: String, expected: Bool) {
        #expect(GeneratedCode.isGenerated(path: "/r/A.swift", header: header) == expected, "\(header)")
    }

    @Test func `only the first headerLength characters of a header are searched`() {
        let padding = String(repeating: "é", count: GeneratedCode.headerLength - "do not edit".count)
        #expect(GeneratedCode.isGenerated(path: "/r/A.swift", header: padding + "do not edit"))
        #expect(!GeneratedCode.isGenerated(path: "/r/A.swift", header: padding + "x" + "do not edit"))
    }

    @Test func `a mark just past the limit changes the last character, and CRLF counts as one`() {
        let ascii = String(repeating: "x", count: GeneratedCode.headerLength - "do not edit".count)
        #expect(GeneratedCode.isGenerated(path: "/r/A.swift", header: ascii + "do not edit" + "zzz"))
        #expect(!GeneratedCode.isGenerated(path: "/r/A.swift", header: ascii + "do not edit\u{301}"))
        let lines = String(repeating: "//\r\n", count: (GeneratedCode.headerLength - "do not edit".count) / 3)
        #expect(lines.utf8.count + "do not edit".count > GeneratedCode.headerLength)
        #expect(GeneratedCode.isGenerated(path: "/r/A.swift", header: lines + "do not edit"))
        #expect(GeneratedCode.isGenerated(path: "/r/A.swift", header: Substring("// DO NOT EDIT")))
    }
}
